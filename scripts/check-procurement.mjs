import assert from 'node:assert/strict';
import { createServer } from 'vite';
const server=await createServer({configFile:false,optimizeDeps:{noDiscovery:true},server:{middlewareMode:true,hmr:false},appType:'custom'});
try {
  const {procurementReference,procurementMaterials,inventoryPlan,procurementMetrics,validatePlan,procurementRemainingStock,datedProcurementMetrics,procurementEditPlan,procurementChoices}=await server.ssrLoadModule('/src/lib/procurement.ts');
  const {RAW_MATERIALS,RAW_MOVEMENTS,rawMaterialBalance}=await server.ssrLoadModule('/src/lib/rawMaterialData.ts');
  const plans=procurementMaterials();
  assert.equal(plans.length,RAW_MATERIALS.length);
  assert.deepEqual(plans.map(p=>p.name),RAW_MATERIALS.map(m=>m.name));
  const raw=RAW_MATERIALS.find(m=>m.openingStock!==null);
  const linked=plans.find(p=>p.materialId===raw.id);
  const source={...raw,currentStock:107};
  const choices=procurementChoices([source],[]);
  assert.equal(procurementEditPlan(choices[0],'2026-10-17').stock,107);
  assert.equal(procurementChoices([{...source,currentStock:0}],[])[0].stock,0);
  assert.equal(procurementChoices([{...source,currentStock:null}],[])[0].stock,null);
  const existing={...choices[0],stock:50,monthly:26,asOfDate:'2026-10-15',version:1};
  assert.equal(procurementEditPlan(procurementChoices([source],[existing])[0],'2026-10-17').stock,50);
  assert.equal(procurementEditPlan(procurementChoices([source],[{...existing,stock:null}])[0],'2026-10-17').stock,null);
  assert.equal(procurementEditPlan(procurementChoices([{...source,currentStock:-2}],[])[0],'2026-10-17').stock,-2);
  const before=inventoryPlan(linked,RAW_MOVEMENTS,'2026-10-17');
  assert.equal(before.stock,rawMaterialBalance(raw,RAW_MOVEMENTS).currentStock);
  const issue={id:'planner-issue',materialId:raw.id,materialName:raw.name,category:raw.category,unit:raw.unit,date:'2026-10-17',movementType:'OUT',quantity:3,reference:'check',remarks:''};
  const afterOut=inventoryPlan(linked,[...RAW_MOVEMENTS,issue],'2026-10-17');
  assert.ok(Math.abs(afterOut.stock-(before.stock-3))<1e-6);
  assert.equal(afterOut.dailyActual,before.dailyActual+3);
  assert.equal(afterOut.actual,before.actual+3);
  assert.equal(afterOut.plan.monthly,before.plan.monthly); // Actual issues never replace manual planning rates.
  const afterIn=inventoryPlan(linked,[...RAW_MOVEMENTS,issue,{...issue,id:'planner-receipt',movementType:'IN',quantity:10}],'2026-10-17');
  assert.ok(Math.abs(afterIn.stock-(before.stock+7))<1e-6);
  assert.equal(afterIn.plan.monthly,afterOut.plan.monthly);
  const unknownPlan=plans.find(p=>RAW_MATERIALS.find(m=>m.id===p.materialId).openingStock===null);
  assert.equal(inventoryPlan(unknownPlan,RAW_MOVEMENTS,'2026-10-17').stock,null);
  const items=procurementReference(),hdpe=items[0];
  const dailyPlan={...hdpe,stock:100,monthly:26,days:26,asOfDate:'2026-10-17'};
  assert.equal(procurementRemainingStock(dailyPlan,'2026-10-17'),100);
  assert.equal(procurementRemainingStock(dailyPlan,'2026-10-18'),100);
  assert.equal(procurementRemainingStock(dailyPlan,'2026-10-22'),100);
  assert.equal(procurementRemainingStock(dailyPlan,'2027-10-17'),100);
  assert.equal(procurementRemainingStock({...dailyPlan,monthly:0},'2027-10-17'),100);
  assert.equal(procurementRemainingStock({...dailyPlan,stock:null},'2026-10-18'),null);
  assert.equal(procurementRemainingStock(dailyPlan,'2026-10-22'),100); // Stock remains a manual figure.
  const dayOne=datedProcurementMetrics(dailyPlan,'2026-10-17'),dayTwo=datedProcurementMetrics(dailyPlan,'2026-10-18');
  assert.equal(dayOne.stockUpto,dayTwo.stockUpto);
  assert.equal(dayOne.reorder,dayTwo.reorder);
  assert.equal(dayTwo.coverage,100);
  assert.equal(dayTwo.stock,100);
  const editing=procurementEditPlan(dailyPlan,'2026-10-22');
  assert.equal(editing.stock,100);
  assert.equal(editing.asOfDate,'2026-10-17');
  assert.equal(procurementRemainingStock(editing,'2026-10-22'),100);
  assert.equal(procurementRemainingStock(editing,'2026-10-23'),100);
  assert.equal(procurementRemainingStock({...editing,monthly:52},'2026-10-23'),100);
  assert.equal(datedProcurementMetrics({...editing,monthly:52},'2026-10-23').coverage,50);
  const manuallyUpdated={...editing,stock:80,asOfDate:'2026-10-22'};
  assert.equal(procurementRemainingStock(manuallyUpdated,'2026-10-23'),80);
  assert.equal(dailyPlan.stock,100); // Opening the editor never changes saved input.
  assert.equal(procurementEditPlan({...dailyPlan,stock:null},'2026-10-22').stock,null);
  assert.equal(procurementEditPlan({...dailyPlan,stock:0},'2026-10-22').stock,0);
  assert.equal(items.length,14);
  const result=procurementMetrics(hdpe,'2026-10-16');
  assert.equal(result.daily,1.03);
  assert.ok(Math.abs(result.coverage-51.213592233)<1e-6);
  assert.equal(result.stockUpto,'2026-12-06');
  assert.equal(result.reorder,'2026-09-22');
  assert.equal(result.status,'Order now');
  assert.equal(procurementMetrics({...hdpe,stock:null},'2026-10-16').status,'Stock unknown');
  assert.equal(procurementMetrics({...hdpe,stock:0},'2026-10-16').status,'Out of stock');
  assert.equal(procurementMetrics({...hdpe,monthly:0},'2026-10-16').coverage,null);
  const deliveries=[{id:'a',supplier:'Test',date:'2026-11-01',quantity:25.5},{id:'b',supplier:'Test',date:'2027-12-01',quantity:25.5},{id:'c',supplier:'Test',date:'2026-10-01',quantity:25.5}];
  const planned=procurementMetrics({...hdpe,deliveries},'2026-10-16');
  assert.equal(planned.deliveries[0].status,'Overdue / confirm receipt');
  assert.equal(planned.deliveries[1].status,'On time');
  assert.equal(planned.deliveries[2].status,'Gap before arrival');
  assert.ok(Math.abs(planned.continuous-(52.75+25.5)/1.03)<1e-9);
  assert.throws(()=>validatePlan({...hdpe,days:0}));
  assert.throws(()=>validatePlan({...hdpe,monthly:NaN}));
  console.log('Passed procurement source figures, coverage, dates, zero/unknown stock, delivery timing and validation.');
} finally { await server.close(); }
