import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';
import { createServer } from 'vite';
import { verifyFrontend } from './finance-preservation.mjs';
verifyFrontend(JSON.parse(readFileSync('scripts/finance-batch3-preservation.json', 'utf8')));
const server = await createServer({ configFile: false, resolve: { alias: { '@': resolve('src') } }, optimizeDeps: { noDiscovery: true }, server: { middlewareMode: true, hmr: false }, appType: 'custom' });
try {
  const data = await server.ssrLoadModule('/src/finance/transactionData.ts');
  const math = await server.ssrLoadModule('/src/finance/transactionMath.ts');
  const { createTransactionService } = await server.ssrLoadModule('/src/finance/transactionService.ts');
  const { createMasters } = await server.ssrLoadModule('/src/finance/masterData.ts');
  const masters = createMasters(), service = createTransactionService();
  const clone = value => JSON.parse(JSON.stringify(value));
  const make = (kind, values) => ({ ...data.newDocument(kind), reference: `DEMO-TEST-${kind.toUpperCase()}`, ...values });
  const line = (quantity = '1', unitPrice = '1000', taxRate = '0') => ({ description: 'Fictional test line', quantity, unitPrice, taxRate });
  const save = doc => { const result = service.save(doc, masters); assert.deepEqual(result.errors, [], JSON.stringify(doc)); return result.id; };
  const reject = (doc, pattern) => { const before = service.read(); const result = service.save(doc, masters); assert.ok(result.errors.some(e => pattern.test(e)), result.errors.join('; ')); assert.deepEqual(service.read(), before, 'Invalid save is atomic and creates no history'); };
  assert.equal(math.scaled('1.25', 3), 1250);
  for (const value of ['', '-1', 'NaN', 'Infinity', '1e3', '1.5', '1000000000001']) assert.equal(math.scaled(value), null);
  assert.deepEqual(math.amountTotals([line('2.5', '1000', '10')]), { subtotal: 2500, tax: 250, total: 2750, valid: true });
  assert.equal(math.amountTotals([line('1', '5', '10')]).tax, 1, 'Half-unit tax rounds up per line');
  assert.equal(math.amountTotals([line('0.5', '1')]).subtotal, 1, 'Half-unit net rounds up per line');
  for (const lines of [[], [line('0')], [line('-1')], [line('1.0001')], [line('1','1','100.01')], [line('1','1','1.001')], [line('1000000000','1000000000')], [line('1','1000000000000'),line('1','1')]]) assert.equal(math.amountTotals(lines).valid, false);
  const original = service.read(); original.documents[0].lines[0].unitPrice = '999';
  assert.equal(math.documentTotal(service.read().documents[0]), 10000);
  assert.notDeepEqual(createTransactionService().read(), original);
  reject({ ...service.read().documents[0], state: 'Draft' }, /read-only/);
  const sales = make('sales-invoice', { party: 'DEMO-P1', source: 'DEMO-OP-SALES-01', lines: [line('2.5','1000','10')] });
  reject({ ...sales, party: 'DEMO-P2' }, /match|Customer/);
  reject({ ...sales, currency: 'USD' }, /currency|UGX/);
  reject({ ...sales, source: 'DEMO-OP-PURCHASE-01' }, /Operational reference/);
  reject({ ...sales, date: '2026-02-30' }, /valid document date/);
  reject({ ...sales, settled: 1 }, /settlement/);
  const salesId = save(sales);
  const purchaseId = save(make('purchase-invoice', { party: 'DEMO-P2', source: 'DEMO-OP-PURCHASE-01', lines: [line('2','1500')] }));
  reject({ ...sales, reference: 'DEMO-TEST-PURCHASE-INVOICE' }, /unique/);
  const receipt = make('receipt', { party: 'DEMO-P1', bank: 'DEMO-B1', amount: '750', allocations: [{ invoice: 'DEMO-FINV-S1', amount: '500' }, { invoice: salesId, amount: '250' }] });
  reject({ ...receipt, amount: '749' }, /equal/);
  reject({ ...receipt, allocations: [{ invoice: 'DEMO-FINV-P1', amount: '750' }] }, /match/);
  reject({ ...receipt, allocations: [{ invoice: 'DEMO-FINV-S1', amount: '500' }, { invoice: 'DEMO-FINV-S1', amount: '250' }] }, /only once/);
  reject({ ...receipt, bank: 'missing' }, /fictional bank/);
  reject({ ...receipt, date: '2026-10-01' }, /precede/);
  const receiptId = save(receipt);
  const credit = make('credit-note', { party: 'DEMO-P1', invoice: salesId, memo: 'Fictional price correction', lines: [line('1','250')] });
  reject({ ...credit, invoice: purchaseId }, /match/);
  reject({ ...credit, memo: '' }, /reason/);
  const creditId = save(credit);
  reject({ ...credit, reference: 'DEMO-EXCESS-NOTE', invoice: 'DEMO-FINV-S1', lines: [line('1','8000')] }, /exceed|below/);
  const debitId = save(make('debit-note', { party: 'DEMO-P2', invoice: purchaseId, memo: 'Fictional supplier adjustment', lines: [line('1','500')] }));
  const paymentId = save(make('payment', { party: 'DEMO-P2', bank: 'DEMO-B1', amount: '500', allocations: [{ invoice: purchaseId, amount: '500' }] }));
  reject({ ...receipt, reference: 'DEMO-EXCESS-RECEIPT', amount: '8000', allocations: [{ invoice: 'DEMO-FINV-S1', amount: '8000' }] }, /exceed|below/);
  const savedSales = service.read().documents.find(d => d.id === salesId);
  reject({ ...savedSales, lines: [line('1','100')] }, /exceed|below/);
  assert.equal(math.invoiceBalance(savedSales, service.read().documents).available, 2250);
  const savedPurchase = service.read().documents.find(d => d.id === purchaseId);
  assert.equal(math.invoiceBalance(savedPurchase, service.read().documents).available, 2000);
  const savedReceipt = service.read().documents.find(d => d.id === receiptId);
  save(savedReceipt); // Editing does not double-count its own allocations.
  const journal = make('journal', { memo: 'Fictional journal', lines: [
    { account: 'DEMO-A3', description: 'Demo debit', debit: '1000', credit: '0' },
    { account: 'DEMO-A2', description: 'Demo credit', debit: '0', credit: '1000' },
  ] });
  reject({ ...journal, lines: [journal.lines[0]] }, /two lines|equal/);
  reject({ ...journal, lines: [journal.lines[0], { ...journal.lines[1], credit: '999' }] }, /equal/);
  reject({ ...journal, lines: [{ ...journal.lines[0], credit: '1000' }, journal.lines[1]] }, /exactly one/);
  reject({ ...journal, lines: [{ ...journal.lines[0], account: 'DEMO-A1' }, journal.lines[1]] }, /non-group/);
  const journalId = save(journal);
  const linked = service.read().documents.find(d => d.id === salesId);
  reject({ ...linked, date: '2026-11-07' }, /precede/);
  reject({ ...journal, id: 'DEMO-UNKNOWN' }, /unknown/);
  reject({ ...linked, kind: 'purchase-invoice', party: 'DEMO-P2', source: 'DEMO-OP-PURCHASE-01' }, /direction/);
  const savedCredit = service.read().documents.find(d => d.id === creditId);
  save({ ...savedCredit, memo: 'Edited local reason' });
  assert.ok(service.read().history.some(e => e.document === creditId && e.action.includes('edited')));
  assert.equal(new Set(service.read().history.map(e => e.sequence)).size, service.read().history.length);
  assert.ok([salesId,purchaseId,receiptId,paymentId,creditId,debitId,journalId].every(id => id.startsWith('DEMO-')));
  console.log('PASS: frontend preservation hashes (cross-repository hashes have a separate explicit check); transaction fixture isolation; scaled rounding/bounds; invoice source/party/currency/date consistency; split allocations, aggregate over-allocation and edits; note direction/caps; journal balancing; read-only snapshots; atomic rejection and local history.');
} finally { await server.close(); }
